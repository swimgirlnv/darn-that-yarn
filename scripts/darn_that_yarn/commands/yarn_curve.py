def generate_yarn_curves(
    add_tubes: bool = False,
    yarn_radius: float = 0.0,
    tube_segments: int = 6,
    row_chunk_size: int = DEFAULT_ROW_CHUNK_SIZE,
    max_points_per_curve: int = DEFAULT_MAX_POINTS_PER_CURVE,
    ui_yield_face_interval: int = DEFAULT_UI_YIELD_FACE_INTERVAL,
    progress_callback: Optional[Callable[[int, str], None]] = None,
) -> List[str]:
    """
    Traverse the stitch mesh stored in STATE and generate one continuous
    Maya NURBS curve (and optionally a tube mesh) per knitting row.

    Algorithm
    ---------
    1. BFS over the face adjacency graph (same logic as apply_pattern_fill)
       to assign (row, col) grid coordinates to every face.
    2. Group faces by row; sort each group by column.
    3. For each row:
         a. Cast-on  – prepend cast-on points for the first row.
         b. Stitches – append per-stitch-type points for every face in order.
         c. Bind-off – append bind-off points for the last row.
    4. Materialise each YarnCurve as a Maya NURBS curve node.
    5. Optionally wrap each curve in a tube mesh via add_tube_geometry().

    Returns a list of curve (or tube) node names.
    """
    # ── Select the right data source depending on tessellation state ──────────
    # After tessellation + shrinkwrap, the live geometry is STATE.preview_mesh
    # with edge/face data in STATE.t_edge_map / STATE.t_face_stitch_map.
    # build_face_context() and _compute_face_dimensions() both read STATE.edge_map
    # directly, so we temporarily promote the tessellated maps to the primary
    # fields for the duration of this call, then restore them on exit.
    _old_face_stitch_map = STATE.face_stitch_map
    _old_edge_map        = STATE.edge_map
    _old_base_mesh       = STATE.base_mesh

    if (
        STATE.preview_mesh
        and cmds.objExists(STATE.preview_mesh)  # type: ignore[attr-defined]
        and STATE.t_face_stitch_map
    ):
        STATE.face_stitch_map = STATE.t_face_stitch_map
        STATE.edge_map        = STATE.t_edge_map
        STATE.base_mesh       = STATE.preview_mesh  # type: ignore[assignment]

    try:
        if progress_callback:
            progress_callback(2, "Generating yarn curves")
        nodes = _generate_yarn_curves_impl(
            add_tubes=add_tubes,
            yarn_radius=yarn_radius,
            tube_segments=tube_segments,
            row_chunk_size=row_chunk_size,
            max_points_per_curve=max_points_per_curve,
            ui_yield_face_interval=ui_yield_face_interval,
            progress_callback=progress_callback,
        )
        if progress_callback:
            progress_callback(98, "Yarn geometry complete")
        return nodes
    finally:
        STATE.face_stitch_map = _old_face_stitch_map
        STATE.edge_map        = _old_edge_map
        STATE.base_mesh       = _old_base_mesh


def _generate_yarn_curves_impl(
    add_tubes: bool,
    yarn_radius: float,
    tube_segments: int,
    row_chunk_size: int,
    max_points_per_curve: int,
    ui_yield_face_interval: int,
    progress_callback: Optional[Callable[[int, str], None]],
) -> List[str]:
    """Internal implementation – always reads from STATE.face_stitch_map / STATE.base_mesh."""
    from collections import deque

    if not STATE.face_stitch_map:
        om.MGlobal.displayError(
            "generate_yarn_curves: no stitch map. Initialise the mesh first."
        )
        return []
    if not STATE.base_mesh:
        om.MGlobal.displayError(
            "generate_yarn_curves: no base mesh. Select a mesh first."
        )
        return []

    _delete_existing_yarn_nodes()

    cmds.select(STATE.base_mesh, replace=True)
    sel = om.MGlobal.getActiveSelectionList()
    if sel.length() == 0:
        om.MGlobal.displayError("generate_yarn_curves: could not select base mesh.")
        return []

    dag_path = sel.getDagPath(0)
    if not dag_path.hasFn(om.MFn.kMesh):
        dag_path.extendToShape()

    # ── Build edge → face map and face adjacency ───────────────────────────
    edge_to_faces: dict = {}
    face_iter = om.MItMeshPolygon(dag_path)
    while not face_iter.isDone():
        fid = face_iter.index()
        if fid in STATE.face_stitch_map:
            for eid in face_iter.getEdges():
                edge_to_faces.setdefault(eid, []).append(fid)
        face_iter.next()

    face_adj: dict = {fid: [] for fid in STATE.face_stitch_map}
    for eid, flist in edge_to_faces.items():
        if len(flist) == 2:
            f0, f1 = flist
            face_adj[f0].append((f1, eid))
            face_adj[f1].append((f0, eid))

    # ── BFS to assign (row, col) coordinates ──────────────────────────────
    face_coords: dict = {}
    start_face = next(iter(STATE.face_stitch_map))
    queue: deque = deque([(start_face, 0, 0)])
    face_coords[start_face] = (0, 0)

    while queue:
        fid, row, col = queue.popleft()
        for nbr_face, shared_edge in face_adj.get(fid, []):
            if nbr_face in face_coords:
                continue
            etype = STATE.edge_map.get(shared_edge, EdgeType.UNASSIGNED)
            if getattr(etype, "name", str(etype)) == "COURSE":
                new_row, new_col = row + 1, col
            else:
                new_row, new_col = row, col + 1  # WALE or unassigned
            face_coords[nbr_face] = (new_row, new_col)
            queue.append((nbr_face, new_row, new_col))

    # ── Group faces by row ─────────────────────────────────────────────────
    rows: dict = {}
    for fid, (row, col) in face_coords.items():
        rows.setdefault(row, []).append((col, fid))
    for row_faces in rows.values():
        row_faces.sort(key=lambda x: x[0])

    if not rows:
        om.MGlobal.displayWarning("generate_yarn_curves: no rows found.")
        return []

    min_row = min(rows)
    max_row = max(rows)

    # ── Generate one curve per row ─────────────────────────────────────────
    created_nodes: List[str] = []

    cmds.refresh(suspend=True)  # type: ignore[attr-defined]
    try:
        _generate_rows(
            rows, min_row, max_row, dag_path, face_adj, add_tubes,
            yarn_radius, tube_segments, created_nodes,
            row_chunk_size=row_chunk_size,
            max_points_per_curve=max_points_per_curve,
            ui_yield_face_interval=ui_yield_face_interval,
            progress_callback=progress_callback,
        )
    finally:
        cmds.refresh(suspend=False)  # type: ignore[attr-defined]
        cmds.refresh()  # type: ignore[attr-defined]

    om.MGlobal.displayInfo(
        f"generate_yarn_curves: created {len(created_nodes)} yarn path(s)."
    )
    return created_nodes


def _generate_rows(
    rows: dict,
    min_row: int,
    max_row: int,
    dag_path,  # om.MDagPath — stubs incomplete
    face_adj: dict,
    add_tubes: bool,
    yarn_radius: float,
    tube_segments: int,
    created_nodes: list,
    row_chunk_size: int,
    max_points_per_curve: int,
    ui_yield_face_interval: int,
    progress_callback: Optional[Callable[[int, str], None]],
) -> None:
    row_chunk_size = max(1, int(row_chunk_size))
    max_points_per_curve = max(8, int(max_points_per_curve))
    ui_yield_face_interval = max(1, int(ui_yield_face_interval))

    total_faces = sum(len(face_list) for face_list in rows.values())
    processed_faces = 0
    processed_rows = 0
    last_reported_progress = 2

    def _emit_progress(status: str) -> None:
        nonlocal last_reported_progress
        if not progress_callback or total_faces <= 0:
            return
        pct = 2 + int((processed_faces * 95) / total_faces)
        pct = max(2, min(97, pct))
        progress_callback(pct, status)
        last_reported_progress = max(last_reported_progress, pct)

    def _yield_ui() -> None:
        # Pump idle events periodically so Maya can remain responsive while
        # generation runs with viewport refresh suspended.
        try:
            maya_utils.processIdleEvents()
            return
        except Exception:
            pass
        cmds.refresh(suspend=False)  # type: ignore[attr-defined]
        cmds.refresh()  # type: ignore[attr-defined]
        cmds.refresh(suspend=True)  # type: ignore[attr-defined]

    # ── Precompute face and row centroids for wale_axis orientation ────────
    # wale_axis direction from edge vectors is arbitrary (depends on edge
    # traversal order).  We correct it here so it always points toward the
    # next row (increasing row index), which makes v=+0.55 consistently
    # extend the loop top into the adjacent row rather than away from it.
    face_centroids: dict = {}
    face_iter_pre = om.MItMeshPolygon(dag_path)  # type: ignore[attr-defined]
    while not face_iter_pre.isDone():
        fid_pre = face_iter_pre.index()
        if fid_pre in STATE.face_stitch_map:
            pts_pre = face_iter_pre.getPoints(om.MSpace.kWorld)  # type: ignore[attr-defined]
            face_centroids[fid_pre] = (
                sum(p.x for p in pts_pre) / len(pts_pre),
                sum(p.y for p in pts_pre) / len(pts_pre),
                sum(p.z for p in pts_pre) / len(pts_pre),
            )
        face_iter_pre.next()

    row_centroids: dict = {}
    for ri, flist_k in rows.items():
        valid_fids = [fid for _, fid in flist_k if fid in face_centroids]
        if valid_fids:
            row_centroids[ri] = (
                sum(face_centroids[f][0] for f in valid_fids) / len(valid_fids),
                sum(face_centroids[f][1] for f in valid_fids) / len(valid_fids),
                sum(face_centroids[f][2] for f in valid_fids) / len(valid_fids),
            )

    face_dimensions: dict = {}
    for flist in rows.values():
        for _, fid in flist:
            if fid in STATE.face_stitch_map and fid not in face_dimensions:
                face_dimensions[fid] = _compute_face_dimensions(dag_path, fid)

    stitch_scales = [
        min(width, height)
        for width, height in face_dimensions.values()
        if width > 1e-6 and height > 1e-6
    ]
    if stitch_scales:
        stitch_scales.sort()
        median_stitch_scale = stitch_scales[len(stitch_scales) // 2]
    else:
        median_stitch_scale = 1.0
    effective_yarn_radius = (
        yarn_radius
        if yarn_radius > 0.0
        else max(DEFAULT_YARN_RADIUS, median_stitch_scale * YARN_RADIUS_STITCH_FRACTION)
    )

    def _row_is_closed(face_list: list) -> bool:
        row_fids = {fid for _, fid in face_list}
        if len(row_fids) < 3:
            return False

        for fid in row_fids:
            wale_neighbor_count = 0
            for nbr_fid, shared_eid in face_adj.get(fid, []):
                if nbr_fid not in row_fids:
                    continue
                etype = STATE.edge_map.get(shared_eid, EdgeType.UNASSIGNED)
                if getattr(etype, "name", str(etype)) == "WALE":
                    wale_neighbor_count += 1
            if wale_neighbor_count < 2:
                return False
        return True

    def _order_closed_row(
        face_list: list,
        preferred_start: Optional[Tuple[float, float, float]] = None,
    ) -> list:
        row_fids = {fid for _, fid in face_list}
        if len(row_fids) < 3:
            return face_list

        wale_neighbors = {fid: [] for fid in row_fids}
        for fid in row_fids:
            for nbr_fid, shared_eid in face_adj.get(fid, []):
                if nbr_fid not in row_fids:
                    continue
                etype = STATE.edge_map.get(shared_eid, EdgeType.UNASSIGNED)
                if getattr(etype, "name", str(etype)) == "WALE":
                    wale_neighbors[fid].append(nbr_fid)

        if preferred_start is None:
            start_fid = face_list[0][1]
        else:
            sx, sy, sz = preferred_start
            start_fid = min(
                row_fids,
                key=lambda fid: (
                    (face_centroids[fid][0] - sx) ** 2
                    + (face_centroids[fid][1] - sy) ** 2
                    + (face_centroids[fid][2] - sz) ** 2
                ),
            )
        ordered_fids = [start_fid]
        prev_fid = None
        cur_fid = start_fid

        while len(ordered_fids) < len(row_fids):
            candidates = [
                nbr for nbr in wale_neighbors.get(cur_fid, [])
                if nbr != prev_fid and nbr not in ordered_fids
            ]
            if not candidates:
                candidates = [
                    nbr for nbr in wale_neighbors.get(cur_fid, [])
                    if nbr not in ordered_fids
                ]
            if not candidates:
                return face_list
            next_fid = candidates[0]
            ordered_fids.append(next_fid)
            prev_fid, cur_fid = cur_fid, next_fid

        return [(idx, fid) for idx, fid in enumerate(ordered_fids)]

    def _materialize_curve(
        curve: YarnCurve,
        row_idx: int,
        closed: bool,
        curve_name: Optional[str] = None,
        tube_name: Optional[str] = None,
    ) -> None:
        def _compact_points(points: List[om.MPoint], eps: float = 1e-8) -> List[om.MPoint]:
            if not points:
                return []
            compacted: List[om.MPoint] = [points[0]]
            for pt in points[1:]:
                prev = compacted[-1]
                dx = pt.x - prev.x
                dy = pt.y - prev.y
                dz = pt.z - prev.z
                if (dx * dx + dy * dy + dz * dz) <= (eps * eps):
                    continue
                compacted.append(pt)
            return compacted

        if curve_name is None:
            curve_name = f"yarn_row_{row_idx:04d}" if closed else "yarn_fabric"
        if tube_name is None:
            tube_name = f"yarn_tube_row_{row_idx:04d}" if closed else "yarn_tube_fabric"

        build_curve = YarnCurve(points=_compact_points(curve.points))
        curve_node = build_curve.build_maya_curve(curve_name, closed=closed)
        if not curve_node:
            return

        if add_tubes:
            try:
                tube_node = add_tube_geometry(
                    curve_node,
                    radius=effective_yarn_radius,
                    tube_segments=tube_segments,
                    name=tube_name,
                )
                if tube_node:
                    STATE.yarn_mesh = tube_node
                    STATE.yarn_uvs_clean = False
                    cmds.hide(curve_node)
                    created_nodes.append(tube_node)
                else:
                    cmds.warning(  # type: ignore[attr-defined]
                        f"yarn tube failed for row {row_idx} ({curve_name}); curve kept."
                    )
                    created_nodes.append(curve_node)
            except Exception as exc:
                cmds.warning(  # type: ignore[attr-defined]
                    f"yarn tube exception row {row_idx} ({curve_name}): {exc}"
                )
                created_nodes.append(curve_node)
        else:
            created_nodes.append(curve_node)

    def _append_row_points(
        row_idx: int,
        face_list: list,
        curve: YarnCurve,
        closed_row: bool = False,
        per_face_callback: Optional[Callable[[YarnCurve], None]] = None,
    ) -> None:
        is_first_row = (row_idx == min_row)
        is_last_row  = (row_idx == max_row)

        # Reference vector: points from current row centroid toward next row.
        # Used to flip wale_axis into a consistent "upward" orientation.
        if row_idx + 1 in row_centroids and row_idx in row_centroids:
            rc_cur  = row_centroids[row_idx]
            rc_next = row_centroids[row_idx + 1]
            wale_ref = (rc_next[0] - rc_cur[0],
                        rc_next[1] - rc_cur[1],
                        rc_next[2] - rc_cur[2])
        elif row_idx - 1 in row_centroids and row_idx in row_centroids:
            rc_cur  = row_centroids[row_idx]
            rc_prev = row_centroids[row_idx - 1]
            wale_ref = (rc_cur[0] - rc_prev[0],
                        rc_cur[1] - rc_prev[1],
                        rc_cur[2] - rc_prev[2])
        else:
            wale_ref = (0.0, 1.0, 0.0)

        # Precompute per-face centroids in this row for course_axis orientation.
        row_face_centers = {
            fid: face_centroids[fid]
            for _, fid in face_list
            if fid in face_centroids
        }

        for face_idx, (_col, fid) in enumerate(face_list):
            face_data = STATE.face_stitch_map.get(fid)
            if face_data is None:
                continue

            ctx    = build_face_context(dag_path, fid)
            width, height = face_dimensions.get(
                fid, _compute_face_dimensions(dag_path, fid)
            )

            # ── Wale axis: ensure it points toward the next row ───────────
            # Without this, v=+0.70 (loop top) can go the wrong direction for
            # half the faces, creating large visual gaps between rows.
            dot = (ctx.wale_axis.x * wale_ref[0]
                   + ctx.wale_axis.y * wale_ref[1]
                   + ctx.wale_axis.z * wale_ref[2])
            if dot < 0:
                ctx.wale_axis = om.MVector(  # type: ignore[attr-defined]
                    -ctx.wale_axis.x, -ctx.wale_axis.y, -ctx.wale_axis.z
                )

            # ── Course axis: ensure it points toward the next face in the row ─
            # Without this, u=+0.35 (exit) can point LEFT for some faces,
            # reversing entry/exit and breaking within-row connections.
            if face_idx + 1 < len(face_list) or closed_row:
                if face_idx + 1 < len(face_list):
                    _, next_fid = face_list[face_idx + 1]
                else:
                    _, next_fid = face_list[0]
                if next_fid in row_face_centers and fid in row_face_centers:
                    cc = row_face_centers[fid]
                    nc = row_face_centers[next_fid]
                    cref_x = nc[0] - cc[0]
                    cref_y = nc[1] - cc[1]
                    cref_z = nc[2] - cc[2]
                    cdot = (ctx.course_axis.x * cref_x
                            + ctx.course_axis.y * cref_y
                            + ctx.course_axis.z * cref_z)
                    if cdot < 0:
                        ctx.course_axis = om.MVector(  # type: ignore[attr-defined]
                            -ctx.course_axis.x,
                            -ctx.course_axis.y,
                            -ctx.course_axis.z,
                        )
            elif face_idx > 0:
                # Last face: point away from previous face.
                _, prev_fid = face_list[face_idx - 1]
                if prev_fid in row_face_centers and fid in row_face_centers:
                    cc = row_face_centers[fid]
                    pc = row_face_centers[prev_fid]
                    cref_x = cc[0] - pc[0]
                    cref_y = cc[1] - pc[1]
                    cref_z = cc[2] - pc[2]
                    cdot = (ctx.course_axis.x * cref_x
                            + ctx.course_axis.y * cref_y
                            + ctx.course_axis.z * cref_z)
                    if cdot < 0:
                        ctx.course_axis = om.MVector(  # type: ignore[attr-defined]
                            -ctx.course_axis.x,
                            -ctx.course_axis.y,
                            -ctx.course_axis.z,
                        )

            # Cast-on once before the first stitch of the row.
            if is_first_row and face_idx == 0:
                append_cast_on_points(curve, width, height, ctx)

            # Main stitch shape (skip NOTASSIGNED faces).
            # Compare by .name to survive module-reload enum identity mismatches.
            if face_data.stitch_type.name != "NOTASSIGNED":
                append_stitch_points(curve, width, height, face_data.stitch_type, ctx)

            # Bind-off once after the last stitch of the row.
            if is_last_row and face_idx == len(face_list) - 1:
                append_bind_off_points(curve, width, height, ctx)

            if per_face_callback:
                per_face_callback(curve)

    # Open cloth uses one continuous strand that snakes across rows.  Tube
    # rows use one open spiral strand: each completed circumference advances
    # to the next row at the seam instead of closing each row as a ring.  This
    # avoids periodic curve chords through the cylinder interior.
    open_curve = YarnCurve()
    open_row_count = 0
    open_segment_index = 1
    spiral_curve = YarnCurve()
    spiral_segment_index = 1
    spiral_start_ref: Optional[Tuple[float, float, float]] = None

    def _next_segment_name(base: str, index: int) -> str:
        if index == 1:
            return base
        return f"{base}_part_{index:04d}"

    def _flush_open_curve(force: bool = False) -> None:
        nonlocal open_segment_index
        if len(open_curve.points) < 2:
            return
        if not force and len(open_curve.points) < max_points_per_curve:
            return

        _materialize_curve(
            open_curve,
            min_row,
            closed=False,
            curve_name=_next_segment_name("yarn_fabric", open_segment_index),
            tube_name=_next_segment_name("yarn_tube_fabric", open_segment_index),
        )
        open_segment_index += 1

        open_curve.points = open_curve.points[-2:] if len(open_curve.points) >= 2 else open_curve.points[-1:]

    def _flush_spiral_curve(force: bool = False) -> None:
        nonlocal spiral_segment_index
        if len(spiral_curve.points) < 2:
            return
        if not force and len(spiral_curve.points) < max_points_per_curve:
            return

        _materialize_curve(
            spiral_curve,
            min_row,
            closed=False,
            curve_name=_next_segment_name("yarn_spiral", spiral_segment_index),
            tube_name=_next_segment_name("yarn_tube_spiral", spiral_segment_index),
        )
        spiral_segment_index += 1

        spiral_curve.points = spiral_curve.points[-2:] if len(spiral_curve.points) >= 2 else spiral_curve.points[-1:]

    def _on_face_processed_open(curve: YarnCurve) -> None:
        nonlocal processed_faces
        processed_faces += 1
        _flush_open_curve(force=False)
        if processed_faces % ui_yield_face_interval == 0:
            _emit_progress(f"Generating yarn ({processed_faces}/{total_faces} faces)")
            _yield_ui()

    def _on_face_processed_spiral(curve: YarnCurve) -> None:
        nonlocal processed_faces
        processed_faces += 1
        _flush_spiral_curve(force=False)
        if processed_faces % ui_yield_face_interval == 0:
            _emit_progress(f"Generating yarn ({processed_faces}/{total_faces} faces)")
            _yield_ui()

    for row_idx in sorted(rows):
        face_list = rows[row_idx]
        is_closed_row = _row_is_closed(face_list)

        if is_closed_row:
            path_faces = _order_closed_row(face_list, spiral_start_ref)
            if path_faces:
                spiral_start_ref = face_centroids.get(path_faces[0][1], spiral_start_ref)
            _append_row_points(
                row_idx,
                path_faces,
                spiral_curve,
                closed_row=True,
                per_face_callback=_on_face_processed_spiral,
            )
        else:
            path_faces = list(face_list)
            if open_row_count % 2 == 1:
                path_faces.reverse()
            _append_row_points(
                row_idx,
                path_faces,
                open_curve,
                per_face_callback=_on_face_processed_open,
            )
            open_row_count += 1

        processed_rows += 1
        if processed_rows % row_chunk_size == 0:
            _emit_progress(f"Generating yarn ({processed_faces}/{total_faces} faces)")
            _yield_ui()

    _flush_open_curve(force=True)
    _flush_spiral_curve(force=True)
