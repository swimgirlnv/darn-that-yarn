# Subtask 1 – YarnCurve struct
# ---------------------------------------------------------------------------

@dataclass
class YarnCurve:
    """
    Stores the ordered control points for a single continuous yarn path.

    Usage
    -----
    curve = YarnCurve()
    append_knit_points(curve, w, h, face_ctx)
    append_purl_points(curve, w, h, next_face_ctx)
    node_name = curve.build_maya_curve("row_0_yarn")
    """

    points: List[om.MPoint] = field(default_factory=list)

    # ------------------------------------------------------------------
    def append(self, pt: om.MPoint) -> None:
        """Append a single control point."""
        self.points.append(pt)

    def extend(self, pts: List[om.MPoint]) -> None:
        """Append multiple control points at once."""
        self.points.extend(pts)

    # ------------------------------------------------------------------
    def build_maya_curve(self, name: str = "yarn_curve", closed: bool = False) -> str:
        """
        Create a Maya NURBS curve from the stored control points.

        Degree-3 (cubic) is used when >= 4 points are available for a
        smooth yarn path; degree-1 (linear) is used as a fallback for
        very short curves.  Returns the transform node name on success,
        or an empty string if there are fewer than 2 points.

        closed : if True, build a periodic (closed-loop) NURBS curve so the
                 yarn wraps continuously around tube/cylinder geometry.  The
                 first and last control points sit on opposite sides of the
                 shared wale edge between the last and first stitch; Maya's
                 periodic NURBS interpolates the connecting arc automatically.
        """
        n = len(self.points)
        if n < 2:
            om.MGlobal.displayWarning("YarnCurve.build_maya_curve: need >= 2 points.")
            return ""

        degree = min(3, n - 1)
        source_points = self.points
        if len(source_points) > MAX_CURVE_POINTS:
            step = int(math.ceil(len(source_points) / MAX_CURVE_POINTS))
            source_points = source_points[::step]
            if source_points[-1] is not self.points[-1]:
                source_points = source_points + [self.points[-1]]

        pts = [(p.x, p.y, p.z) for p in source_points]

        if closed and degree == 3:
            # per=True creates a periodic cubic NURBS that closes smoothly.
            # Maya connects the last CV back to the first, forming the
            # connecting arc that wraps the yarn around the back of the tube.
            return cmds.curve(p=pts, d=degree, per=True, name=name)

        # Use edit points for open rows so the yarn actually passes through
        # the authored over/under pull-through positions.  CV-only curves can
        # visually smooth past those constraints and make rows look stacked.
        return cmds.curve(ep=pts, d=degree, name=name)


