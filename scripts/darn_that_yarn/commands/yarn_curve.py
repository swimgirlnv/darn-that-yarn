def _delete_existing_yarn_nodes() -> None:
    """Remove yarn generated by previous runs so stale rows do not remain."""
    to_delete = []
    for prefix in YARN_NODE_PREFIXES:
        to_delete.extend(cmds.ls(prefix + "*", type="transform") or [])

    if to_delete:
        cmds.delete(sorted(set(to_delete)))


def _delete_existing_yarn_tubes() -> None:
    """Remove generated tube meshes while keeping source yarn curves."""
    to_delete = []
    for prefix in YARN_TUBE_PREFIXES:
        to_delete.extend(cmds.ls(prefix + "*", type="transform") or [])

    if to_delete:
        cmds.delete(sorted(set(to_delete)))


def update_yarn_tube_radius(radius: float, tube_segments: int = 8) -> List[str]:
    """Rebuild existing yarn tube meshes from hidden yarn curves at a new radius."""
    radius = max(0.001, float(radius))
    _delete_existing_yarn_tubes()

    rebuilt: List[str] = []
    for prefix in YARN_CURVE_PREFIXES:
        for curve_node in cmds.ls(prefix + "*", type="transform") or []:
            shapes = cmds.listRelatives(curve_node, shapes=True, type="nurbsCurve") or []
            if not shapes:
                continue
            if curve_node.startswith("yarn_row_"):
                tube_name = curve_node.replace("yarn_row_", "yarn_tube_row_", 1)
            elif curve_node.startswith("yarn_fabric"):
                tube_name = curve_node.replace("yarn_fabric", "yarn_tube_fabric", 1)
            elif curve_node.startswith("yarn_spiral"):
                tube_name = curve_node.replace("yarn_spiral", "yarn_tube_spiral", 1)
            else:
                tube_name = "yarn_tube"

            try:
                tube_node = add_tube_geometry(
                    curve_node,
                    radius=radius,
                    tube_segments=tube_segments,
                    name=tube_name,
                )
                STATE.yarn_mesh = tube_node
                STATE.yarn_uvs_clean = False
            except Exception as exc:
                cmds.warning(  # type: ignore[attr-defined]
                    f"update_yarn_tube_radius: failed on {curve_node}: {exc}"
                )
                tube_node = ""
            if tube_node:
                cmds.hide(curve_node)
                rebuilt.append(tube_node)

    return rebuilt


