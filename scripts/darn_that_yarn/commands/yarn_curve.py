@dataclass
class FaceContext:
    """
    World-space coordinate frame for a single stitch face.

    Attributes
    ----------
    center      : Face centroid in world space.
    course_axis : Unit vector pointing in the course (left→right) direction.
    wale_axis   : Unit vector pointing in the wale (bottom→top) direction.
    normal      : Outward unit face normal.
    dag_path    : DAG path of the mesh (for adjacency queries via MItMeshPolygon).
    face_id     : Integer index of this face on the mesh.
    """

    center: om.MPoint
    course_axis: om.MVector
    wale_axis: om.MVector
    normal: om.MVector
    dag_path: om.MDagPath
    face_id: int


def build_face_context(dag_path: om.MDagPath, face_id: int) -> FaceContext:
    """
    Build a FaceContext for *face_id* on *dag_path*.

    course_axis is the mean direction of the face's COURSE edges.
    wale_axis   is the mean direction of the face's WALE edges.
    normal      is course_axis × wale_axis (outward if labelling is consistent).
    """
    mesh_fn = om.MFnMesh(dag_path)
    edge_iter = om.MItMeshEdge(dag_path)
    face_iter = om.MItMeshPolygon(dag_path)
    face_iter.setIndex(face_id)

    # Face centroid – mean of world-space vertex positions.
    pts = face_iter.getPoints(om.MSpace.kWorld)
    cx = sum(p.x for p in pts) / len(pts)
    cy = sum(p.y for p in pts) / len(pts)
    cz = sum(p.z for p in pts) / len(pts)
    center = om.MPoint(cx, cy, cz)

    course_acc = om.MVector(0.0, 0.0, 0.0)
    course_count = 0
    wale_acc = om.MVector(0.0, 0.0, 0.0)
    wale_count = 0

    for eid in face_iter.getEdges():
        etype = STATE.edge_map.get(eid, EdgeType.UNASSIGNED)
        if getattr(etype, "name", str(etype)) == "UNASSIGNED":
            continue

        edge_iter.setIndex(eid)
        v0 = mesh_fn.getPoint(edge_iter.vertexId(0), om.MSpace.kWorld)
        v1 = mesh_fn.getPoint(edge_iter.vertexId(1), om.MSpace.kWorld)
        d = om.MVector(v1.x - v0.x, v1.y - v0.y, v1.z - v0.z)
        length = d.length()
        if length < 1e-8:
            continue
        d /= length  # normalise

        ename = getattr(etype, "name", str(etype))
        if ename == "COURSE":
            # Opposite face edges traverse antiparallel; flip so they reinforce.
            if course_count > 0 and (
                d.x * course_acc.x + d.y * course_acc.y + d.z * course_acc.z
            ) < 0:
                d = om.MVector(-d.x, -d.y, -d.z)
            course_acc += d
            course_count += 1
        elif ename == "WALE":
            if wale_count > 0 and (
                d.x * wale_acc.x + d.y * wale_acc.y + d.z * wale_acc.z
            ) < 0:
                d = om.MVector(-d.x, -d.y, -d.z)
            wale_acc += d
            wale_count += 1

    # Normalise accumulated directions; fall back to world axes if degenerate.
    if course_count > 0 and course_acc.length() > 1e-8:
        course_axis = course_acc.normalize()
    else:
        course_axis = om.MVector(1.0, 0.0, 0.0)

    if wale_count > 0 and wale_acc.length() > 1e-8:
        wale_axis = wale_acc.normalize()
    else:
        wale_axis = om.MVector(0.0, 1.0, 0.0)

    # Use the actual polygon face normal so depth offsets always point outward.
    mesh_fn2 = om.MFnMesh(dag_path)  # type: ignore[attr-defined]
    try:
        fn = mesh_fn2.getPolygonNormal(face_id, om.MSpace.kWorld)  # type: ignore[attr-defined]
        normal = om.MVector(fn.x, fn.y, fn.z)  # type: ignore[attr-defined]
        if normal.length() < 1e-8:
            raise ValueError("zero normal")
        normal = normal.normalize()
    except Exception:
        # Fallback: cross product of detected axes.
        normal = course_axis ^ wale_axis
        if normal.length() < 1e-8:
            normal = om.MVector(0.0, 0.0, 1.0)
        else:
            normal = normal.normalize()

    return FaceContext(
        center=center,
        course_axis=course_axis,
        wale_axis=wale_axis,
        normal=normal,
        dag_path=dag_path,
        face_id=face_id,
    )



def _face_pt(
    ctx: FaceContext,
    u: float,
    v: float,
    n: float,
    width: float,
    height: float,
) -> om.MPoint:
    """
    Map normalised face-local coordinates (u, v, n) to world space.

    Convention
    ----------
    u  in [-0.5, +0.5]  →  fraction of face width  in the course direction
    v  in [-0.5, +0.5]  →  fraction of face height in the wale direction
    n  in [-0.5, +0.5]  →  depth offset along the face normal, scaled by
                            0.25 × face diagonal for realistic loop depth

    Direct bilinear interpolation using the face's course/wale/normal frame.
    This is stable for all query positions including boundary points (v = ±0.5).
    """
    # depth_scale is proportional to row height so loop depth looks consistent
    # regardless of stitch aspect ratio.  n=1.0 pushes one full row-height in/out.
    depth_scale = height * 0.6
    cx = (
        ctx.center.x
        + ctx.course_axis.x * (u * width)
        + ctx.wale_axis.x   * (v * height)
        + ctx.normal.x      * (n * depth_scale)
    )
    cy = (
        ctx.center.y
        + ctx.course_axis.y * (u * width)
        + ctx.wale_axis.y   * (v * height)
        + ctx.normal.y      * (n * depth_scale)
    )
    cz = (
        ctx.center.z
        + ctx.course_axis.z * (u * width)
        + ctx.wale_axis.z   * (v * height)
        + ctx.normal.z      * (n * depth_scale)
    )
    return om.MPoint(cx, cy, cz)


def _compute_face_dimensions(dag_path: om.MDagPath, face_id: int) -> Tuple[float, float]:
    """
    Return (width, height) for *face_id* where width is the mean length of
    COURSE edges and height is the mean length of WALE edges.
    Falls back to a uniform estimate from the face area if edge lengths are
    not meaningful.
    """
    mesh_fn = om.MFnMesh(dag_path)
    edge_iter = om.MItMeshEdge(dag_path)
    face_iter = om.MItMeshPolygon(dag_path)
    face_iter.setIndex(face_id)

    course_lengths: List[float] = []
    wale_lengths: List[float] = []

    for eid in face_iter.getEdges():
        etype = STATE.edge_map.get(eid, EdgeType.UNASSIGNED)
        edge_iter.setIndex(eid)
        v0 = mesh_fn.getPoint(edge_iter.vertexId(0), om.MSpace.kWorld)
        v1 = mesh_fn.getPoint(edge_iter.vertexId(1), om.MSpace.kWorld)
        length = math.sqrt(
            (v1.x - v0.x) ** 2 + (v1.y - v0.y) ** 2 + (v1.z - v0.z) ** 2
        )
        ename = getattr(etype, "name", str(etype))
        if ename == "COURSE":
            course_lengths.append(length)
        elif ename == "WALE":
            wale_lengths.append(length)

    width  = sum(course_lengths) / len(course_lengths) if course_lengths else 1.0
    height = sum(wale_lengths)   / len(wale_lengths)   if wale_lengths   else 1.0
    return width, height


# ---------------------------------------------------------------------------
# Subtask 2 – Per-stitch-type point generation
# ---------------------------------------------------------------------------
# Local coordinate convention for all canonical point sets:
#   u  – course direction:  -0.5 = left wale edge,   +0.5 = right wale edge
#   v  – wale direction:    -0.5 = bottom course edge, +0.5 = top course edge
#   n  – normal depth:      negative = behind fabric,  positive = in front
#
# The stitch-mesh paper permits any stitch model with one yarn crossover on
# each wale edge and two yarn crossovers on each course edge.  The canonical
# quad templates below keep those constraints explicit: first/last points are
# the wale crossovers, and the body includes two points on v=-0.5 and two on
# v=+0.5.  This gives adjacent rows actual over/under crossing locations
# instead of visual loops that only sit on top of one another.
#
# Each function appends its points to the supplied YarnCurve.  The last point
# of face N and the first point of face N+1 sit on their shared wale edge, so
# the NURBS interpolation naturally connects adjacent stitches in a course.
# ---------------------------------------------------------------------------

WALE_LEFT = -0.50
WALE_RIGHT = 0.50
COURSE_BOTTOM = -0.50
COURSE_TOP = 0.50


def _append_local_points(
    curve: YarnCurve,
    width: float,
    height: float,
    face: FaceContext,
    local_points: List[Tuple[float, float, float]],
) -> None:
    for u, v, n in local_points:
        curve.append(_face_pt(face, u, v, n, width, height))


def append_knit_points(
    curve: YarnCurve,
    width: float,
    height: float,
    face: FaceContext,
    lower_face: Optional[FaceContext] = None,
    lower_width: float = 0.0,
    lower_height: float = 0.0,
) -> None:
    """
    Knit stitch – lower loop is pulled from back to front.

    The two bottom course-edge crossings tuck behind the older loop, then the
    strand comes forward into the visible V.  The two top course-edge crossings
    tuck behind the fabric to leave a receiving loop for the next row.
    """
    if lower_face is not None and lower_width > 0.0 and lower_height > 0.0:
        # Use the face below for the bottom course crossings.  Those points
        # sit in the top of the older loop, so the current yarn is visibly
        # pulled through the previous row instead of floating inside only its
        # own face.
        pts = [
            _face_pt(face, WALE_LEFT, -0.02, -0.26, width, height),
            _face_pt(face, -0.34, COURSE_TOP, -0.38, width, height),
            _face_pt(face, -0.28, 0.25, 0.34, width, height),
            _face_pt(lower_face, -0.18, COURSE_TOP, -0.44, lower_width, lower_height),
            _face_pt(face, 0.00, -0.26, 0.86, width, height),
            _face_pt(lower_face, 0.18, COURSE_TOP, -0.44, lower_width, lower_height),
            _face_pt(face, 0.28, 0.25, 0.34, width, height),
            _face_pt(face, 0.34, COURSE_TOP, -0.38, width, height),
            _face_pt(face, WALE_RIGHT, -0.02, -0.26, width, height),
        ]
        curve.extend(pts)
    else:
        LOCAL: List[Tuple[float, float, float]] = [
            (WALE_LEFT,    -0.02, -0.26),  # single left-wale crossover
            (-0.34, COURSE_TOP, -0.38),    # first top course crossover
            (-0.28,  0.25,  0.34),         # left shoulder visible on the front
            (-0.18, COURSE_BOTTOM, -0.38), # first bottom course crossover
            ( 0.00, -0.26,  0.82),         # back-to-front pull-through
            ( 0.18, COURSE_BOTTOM, -0.38), # second bottom course crossover
            ( 0.28,  0.25,  0.34),         # right shoulder visible on the front
            ( 0.34, COURSE_TOP, -0.38),    # second top course crossover
            (WALE_RIGHT,   -0.02, -0.26),  # single right-wale crossover
        ]
        _append_local_points(curve, width, height, face, LOCAL)


def append_purl_points(
    curve: YarnCurve,
    width: float,
    height: float,
    face: FaceContext,
    lower_face: Optional[FaceContext] = None,
    lower_width: float = 0.0,
    lower_height: float = 0.0,
) -> None:
    """
    Purl stitch – lower loop is pulled from front to back.

    Compared with knit, the pull-through pinches toward the back while the
    front strand forms the pearl bump.  The edge crossing counts match the same
    stitch-mesh topology as knit, only with reversed depth ordering.
    """
    if lower_face is not None and lower_width > 0.0 and lower_height > 0.0:
        pts = [
            _face_pt(face, WALE_LEFT, -0.02, 0.24, width, height),
            _face_pt(face, -0.34, COURSE_TOP, 0.32, width, height),
            _face_pt(face, -0.26, 0.12, 0.72, width, height),
            _face_pt(lower_face, -0.18, COURSE_TOP, 0.42, lower_width, lower_height),
            _face_pt(face, 0.00, -0.20, -0.78, width, height),
            _face_pt(lower_face, 0.18, COURSE_TOP, 0.42, lower_width, lower_height),
            _face_pt(face, 0.26, 0.12, 0.72, width, height),
            _face_pt(face, 0.34, COURSE_TOP, 0.32, width, height),
            _face_pt(face, WALE_RIGHT, -0.02, 0.24, width, height),
        ]
        curve.extend(pts)
    else:
        LOCAL: List[Tuple[float, float, float]] = [
            (WALE_LEFT,    -0.02,  0.24),  # single left-wale crossover
            (-0.34, COURSE_TOP,  0.32),    # first top course crossover
            (-0.26,  0.12,  0.72),         # pearl bump rises forward
            (-0.18, COURSE_BOTTOM,  0.32), # first bottom course crossover
            ( 0.00, -0.20, -0.74),         # front-to-back pull-through
            ( 0.18, COURSE_BOTTOM,  0.32), # second bottom course crossover
            ( 0.26,  0.12,  0.72),         # pearl bump returns
            ( 0.34, COURSE_TOP,  0.32),    # second top course crossover
            (WALE_RIGHT,   -0.02,  0.24),  # single right-wale crossover
        ]
        _append_local_points(curve, width, height, face, LOCAL)


def append_yarnover_points(
    curve: YarnCurve,
    width: float,
    height: float,
    face: FaceContext,
) -> None:
    """
    Yarn-over stitch – the yarn wraps without being pulled through a loop.

    This preserves the same edge crossing topology as a quad stitch but leaves
    the middle open so the resulting fabric has a visible eyelet.
    """
    LOCAL: List[Tuple[float, float, float]] = [
        (WALE_LEFT,    -0.02,  0.10),  # single left-wale crossover
        (-0.34, COURSE_TOP,  0.28),    # first top course crossover
        (-0.18,  0.18,  0.62),         # yarn-over wrap rises in front
        (-0.18, COURSE_BOTTOM,  0.18), # first bottom course crossover
        ( 0.00, -0.02, -0.28),         # back-side pinch leaves an eyelet
        ( 0.18, COURSE_BOTTOM,  0.18), # second bottom course crossover
        ( 0.18,  0.18,  0.62),         # front wrap returns
        ( 0.34, COURSE_TOP,  0.28),    # second top course crossover
        (WALE_RIGHT,   -0.02,  0.10),  # single right-wale crossover
    ]
    _append_local_points(curve, width, height, face, LOCAL)


def append_increase_points(
    curve: YarnCurve,
    width: float,
    height: float,
    face: FaceContext,
) -> None:
    """
    Increase stitch (5-edge face) – one incoming strand is worked into two loops,
    widening the fabric by one stitch.

    The wider pentagon face accommodates a slightly fanned-out loop shape; the
    entry and exit are shifted toward the two outgoing course edges.
    """
    LOCAL: List[Tuple[float, float, float]] = [
        (-0.42, -0.34,  0.26),  # incoming strand from one lower loop
        (-0.22, -0.42, -0.62),  # behind the lower loop
        (-0.04, -0.34,  0.38),  # pulled through to front
        (-0.28, -0.02, -0.16),  # first new leg
        (-0.12,  0.44, -0.40),  # top-left of widened loop
        ( 0.10,  0.62, -0.42),  # shared top reaches toward two upper stitches
        ( 0.32,  0.44, -0.40),  # top-right of widened loop
        ( 0.42, -0.02, -0.16),  # second new leg
        ( 0.12, -0.34,  0.38),  # front side of pull-through window
        ( 0.30, -0.42, -0.62),  # behind the lower loop before exit
        ( 0.50, -0.34,  0.26),  # exit to the extra stitch position
    ]
    for u, v, n in LOCAL:
        curve.append(_face_pt(face, u, v, n, width, height))


def append_decrease_points(
    curve: YarnCurve,
    width: float,
    height: float,
    face: FaceContext,
) -> None:
    """
    Decrease stitch (5-edge face) – two incoming strands are knit together into
    one loop, narrowing the fabric by one stitch.

    The entry is shifted left to represent the wider incoming side, and the
    merged loop rises to a single peak before exiting.
    """
    LOCAL: List[Tuple[float, float, float]] = [
        (-0.50, -0.34,  0.26),  # entry from the first lower loop
        (-0.34, -0.42, -0.62),  # behind first lower loop
        (-0.16, -0.34,  0.38),  # front side of first pull-through
        (-0.02, -0.42, -0.62),  # behind second lower loop
        ( 0.16, -0.34,  0.38),  # front side of second pull-through
        (-0.32,  0.05, -0.16),  # two incoming strands merge
        (-0.15,  0.44, -0.40),  # merged loop left shoulder
        ( 0.00,  0.62, -0.42),  # single top loop
        ( 0.15,  0.44, -0.40),  # merged loop right shoulder
        ( 0.28,  0.05, -0.16),  # outgoing strand descends
        ( 0.10, -0.34,  0.38),  # front side of exit window
        ( 0.28, -0.42, -0.62),  # behind lower loop before exit
        ( 0.42, -0.34,  0.26),  # exit as one stitch
    ]
    for u, v, n in LOCAL:
        curve.append(_face_pt(face, u, v, n, width, height))


